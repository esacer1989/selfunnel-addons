#!/usr/bin/env bashio
# Selfunnel addon: validate install_token -> generate frpc.toml -> run frpc
set -euo pipefail

OPTS=/data/options.json
# bashio::config goes через Supervisor API; в HA 2026.9.x бывает "Invalid token",
# поэтому читаем /data/options.json напрямую (jq) — отказоустойчиво.
ADDON_VERSION="1.1.0"

if ! jq -e . "$OPTS" >/dev/null 2>&1; then
    bashio::log.fatal "$OPTS не найден — нет прав на /data? Сообщи в поддержку selfunnel"
    exit 1
fi
INSTALL_TOKEN=$(jq -r '.install_token // ""' "$OPTS")
SUBDOMAIN_OPT=$(jq -r '.subdomain // ""' "$OPTS")
LOCAL_HOST=$(jq -r '.local_host // "homeassistant"' "$OPTS")
LOCAL_PORT=$(jq -r '.local_port // 8123' "$OPTS" 2>/dev/null || echo 8123)
# jq с нечисловым local_port больше не роняет скрипт: числовую валидацию делает блок ниже.
LOG_LEVEL=$(jq -r '.log_level // "info"' "$OPTS")

API_URL="https://selfunnel.ru/api/addon/validate"
DELAYS=(2 5 10 20 30)

if [ -z "$INSTALL_TOKEN" ]; then
    bashio::log.error "Не задан install_token — возьми его в кабинете selfunnel (кнопка «Показать install-токен»)"
    exit 1
fi

# Валидация опций перед генерацией frpc.toml (защита от TOML-инъекции кавычками/переносами
# в конфиге от перепутанного поля options).
if ! [[ "$LOG_LEVEL" =~ ^(info|warn|error|debug)$ ]]; then
    bashio::log.error "log_level: допустимые значения info|warn|error|debug — выкат получил: '$LOG_LEVEL'"
    exit 1
fi
if ! [[ "$LOCAL_PORT" =~ ^[0-9]+$ ]] || [ "$LOCAL_PORT" -ge 65536 ] || [ "$LOCAL_PORT" -eq 0 ]; then
    bashio::log.error "local_port должен быть числом 1..65535 — получил: '$LOCAL_PORT'"
    exit 1
fi
if ! [[ "$LOCAL_HOST" =~ ^[A-Za-z0-9][A-Za-z0-9.\-]{0,253}[A-Za-z0-9]$|^localhost$ ]]; then
    bashio::log.error "local_host: разрешены только буквы/цифры/точка/дефис — получил небезопасное значение"
    exit 1
fi

bashio::log.info "Проверка токена у selfunnel..."
HTTP_CODE="000"
RESP=""
for i in 0 1 2 3 4; do
    RESP=$(curl -fsS -A "selfunnel-addon/${ADDON_VERSION}" -X POST "$API_URL" \
             -H "Content-Type: application/json" \
             -d "{\"install_token\":\"$INSTALL_TOKEN\"}" 2>/dev/null) \
        && HTTP_CODE=200 || HTTP_CODE=$?
    if [ "$HTTP_CODE" = "200" ]; then break; fi
    if [ "$HTTP_CODE" = "401" ]; then
        bashio::log.error "install_token недействителен — проверь в кабинете selfunnel"
        exit 1
    fi
    if [ "$i" -lt 4 ]; then
        bashio::log.warning "selfunnel недоступен (HTTP $HTTP_CODE), повтор через ${DELAYS[$i]}с"
        sleep "${DELAYS[$i]}"
    fi
done

if [ "$HTTP_CODE" != "200" ]; then
    bashio::log.error "Не удалось связаться с selfunnel (HTTP $HTTP_CODE) — проверь интернет"
    exit 1
fi
RESP_FILE="/tmp/frpc_validate.json"
printf '%s' "$RESP" > "$RESP_FILE"
chmod 600 "$RESP_FILE"

VALID=$(jq -r '.valid // false' "$RESP_FILE")
if [ "$VALID" != "true" ]; then
    bashio::log.error "install_token недействителен — проверь в кабинете selfunnel"
    rm -f "$RESP_FILE"; exit 1
fi

FRP_TOKEN=$(jq -r '.frp_token // ""' "$RESP_FILE")
API_SUB=$(jq -r '.subdomain // ""' "$RESP_FILE")
rm -f "$RESP_FILE"

if [ -z "$FRP_TOKEN" ]; then
    bashio::log.error "Сервис не выдал frp_token — сообщи в поддержку selfunnel"
    exit 1
fi

# trim
FINAL_SUB="${SUBDOMAIN_OPT//[[:space:]]/}"
[ -z "$FINAL_SUB" ] && FINAL_SUB="${API_SUB//[[:space:]]/}"
if [ -z "$FINAL_SUB" ]; then
    bashio::log.error "Нет поддомена: создай туннель в кабинете selfunnel и перезапусти аддон"
    exit 1
fi

# Поддомен: только [a-z0-9-] (то же ограничение, что и на бэке tunnel_manager._clean).
if ! [[ "$FINAL_SUB" =~ ^[a-z0-9][a-z0-9-]{0,38}[a-z0-9]$ ]]; then
    bashio::log.error "Недопустимый поддомен '$FINAL_SUB' (разрешены строчные латинские буквы, цифры и дефис)"
    exit 1
fi

CONF=/data/frpc.toml
cat > "$CONF" <<EOF
# Auto-generated by Selfunnel addon. Do not share.
serverAddr = "selfunnel.ru"
serverPort = 7000
auth.method = "token"
auth.token = "$FRP_TOKEN"
loginFailExit = false
log.level = "$LOG_LEVEL"
log.to = "console"
transport.tls.enable = true

[[proxies]]
name = "homeassistant"
type = "http"
localIP = "$LOCAL_HOST"
localPort = $LOCAL_PORT
subdomain = "$FINAL_SUB"
EOF
chmod 600 "$CONF"

bashio::log.info "Туннель запущен: https://${FINAL_SUB}.selfunnel.ru"
exec /usr/local/bin/frpc -c "$CONF"
